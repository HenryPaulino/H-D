Object.values(messages).forEach((category) => {
  category.messages = [category.messages.join(' ')]
})

// Retorna uma mensagem aleatória de uma categoria
export const getRandomMessage = (category) => {
  const categoryData = messages[category]

  if (!categoryData || !categoryData.messages.length) {
    return 'Eu só queria lembrar que você é muito especial para mim. ❤️'
  }

  const randomIndex = Math.floor(
    Math.random() * categoryData.messages.length
  )

  return categoryData.messages[randomIndex]
}

// Retorna todas as categorias
export const getCategories = () => {
  return Object.entries(messages).map(([id, data]) => ({
    id,
    emoji: data.emoji,
    title: data.title
  }))
}